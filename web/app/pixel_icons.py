TINTS = {"o": 0.3}  # pixel character -> opacity


def _path(rows: list[str], char: str = "#") -> str:
    """One path, one rectangle per horizontal run of pixels drawn with char."""
    d = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] != char:
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == char:
                x += 1
            d.append(f"M{start} {y}h{x - start}v1h-{x - start}z")
    return "".join(d)


def _viewbox(rows: list[str]) -> str:
    """9 x 9 frame shifted by half the empty margin difference, so every drawing sits exactly in the middle
    (a drawing with 0 empty column on the left and 2 on the right moves by one pixel); the scale stays the
    same for every icon, so their pixels keep the same size side by side."""
    xs = [x for row in rows for x, c in enumerate(row) if c != "."]
    ys = [y for y, row in enumerate(rows) if row.strip(".")]
    dx = (min(xs) - (len(rows[0]) - 1 - max(xs))) / 2
    dy = (min(ys) - (len(rows) - 1 - max(ys))) / 2
    return f"{dx:g} {dy:g} 9 9"


def _inner(rows: list[str]) -> str:
    """The drawing's paths: the solid pixels, then each tint at its opacity."""
    out = f'<path d="{_path(rows)}"/>'
    for char, opacity in TINTS.items():
        if any(char in row for row in rows):
            out += f'<path d="{_path(rows, char)}" opacity="{opacity:g}"/>'
    return out


_PATHS = {name: _path(rows) for name, rows in BITMAPS.items()}
INNER = {name: _inner(rows) for name, rows in BITMAPS.items()}
VIEWBOXES = {name: _viewbox(rows) for name, rows in BITMAPS.items()}


def pixel_svg(name: str, size: int | None = 18, attrs: str = "") -> Markup:
    """Inline SVG of a pixel icon; attrs is extra raw attributes (class, style, aria-*)."""
    size_attrs = f' width="{size}" height="{size}"' if size else ""
    return Markup(
        f'<svg{size_attrs} viewBox="{VIEWBOXES[name]}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" data-px="{name}"'
        f'{(" " + attrs) if attrs else ""}>{INNER[name]}</svg>'
    )


def fingerprint(inner_svg: str) -> str:
    s = re.sub(r"\s+", " ", inner_svg).strip().replace(" />", "/>").replace("> <", "><")
    return hashlib.md5(s.encode()).hexdigest()[:12]


def name_for_lucide(inner_svg: str) -> str | None:
    return LUCIDE.get(fingerprint(inner_svg))


def from_lucide(inner_svg: str) -> str | None:
    """Pixel path data for a former Lucide drawing (None when it has no pixel version)."""
    name = name_for_lucide(inner_svg)
    return _PATHS[name] if name else None
